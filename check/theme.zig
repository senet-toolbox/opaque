pub var mode: Mode = .light;

pub export fn setTheme(new_mode: Mode) void {
    mode = new_mode;
}

pub fn toggleTheme() void {
    mode = switch (mode) {
        .dark => .light,
        .light => .dark,
    };
    Vapor.lib.store("theme", @tagName(mode));
    Vapor.lib.toggleTheme();
}
